const exact: Record<Locale, LocaleMap> = {
  en: {},
  fr: { ...fr, ...extraFr, ...fleetFr, ...drillingFr, ...projectsFr, ...stage8Fr },
  ar: { ...ar, ...extraAr, ...fleetAr, ...drillingAr, ...projectsAr, ...stage8Ar },
};
const originalText = new WeakMap<Node, string>();
const lastLocalizedText = new WeakMap<Node, string>();
const originalAttributes = new WeakMap<Element, Record<string, string>>();

export interface MissingTranslationReport {
  word: string;
  locale: Locale;
  count: number;
}

const missingTranslationLog: MissingTranslationReport[] = [];
const warnedMissingWords = new Set<string>();

function isProbablyTranslatable(word: string): boolean {
  if (word.length < 3) return false;
  if (/[0-9@_]/.test(word)) return false;
  if (word === word.toUpperCase()) return false;
  return true;
}

/**
 * Development-only missing-translation signal. Records source words that
 * survive lookup entirely (no exact, direct, or capitalized hit) so gaps
 * surface in the console / via getMissingTranslations() instead of silently
 * rendering English inside French/Arabic UI. No-op in production builds.
 */
function reportMissingWord(word: string, locale: Locale): void {
  if (typeof process !== "undefined" && process.env?.NODE_ENV === "production") return;
  if (!isProbablyTranslatable(word)) return;
  const key = `${locale}::${word}`;
  const existing = missingTranslationLog.find((entry) => entry.word === word && entry.locale === locale);
  if (existing) {
    existing.count += 1;
    return;
  }
  missingTranslationLog.push({ word, locale, count: 1 });
  if (!warnedMissingWords.has(key)) {
    warnedMissingWords.add(key);
    if (typeof console !== "undefined" && typeof console.warn === "function") {
      console.warn(`[i18n] missing ${locale} translation for word: "${word}"`);
    }
  }
}

export function getMissingTranslations(): MissingTranslationReport[] {
  return missingTranslationLog;
}

function lookupWord(word: string, locale: Locale): string | null {
  const lexicon = sharedLexicon[locale as Exclude<Locale, "en">];
  if (!lexicon) return null;
  const direct = lexicon[word];
  if (direct) return direct;
  const first = word[0];
  const rest = word.slice(1);
  if (first >= "a" && first <= "z") {
    const capitalized = first.toUpperCase() + rest;
    const fallback = lexicon[capitalized];
    if (fallback) return fallback;
  } else if (first >= "A" && first <= "Z" && rest === rest.toLowerCase()) {
    const lowered = first.toLowerCase() + rest;
    const fallback = lexicon[lowered];
    if (fallback) return fallback;
  }
  return null;
}

export function translateText(value: string, locale: Locale): string {
  if (locale === "en" || !value || !value.trim()) return value;
  const whitespaceStart = value.match(/^\s*/)?.[0] || "";
  const whitespaceEnd = value.match(/\s*$/)?.[0] || "";
  const core = value.trim();

  if (/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(core)) return value;

  const maximumDuration = core.match(/^Maximum duration is (\d+) minutes$/);
  if (maximumDuration) {
    const translated = locale === "fr"
      ? `La durée maximale est de ${maximumDuration[1]} minutes`
      : `المدة القصوى هي ${maximumDuration[1]} دقيقة`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const recordCount = core.match(/^(\d+) records · Updated just now$/);
  if (recordCount) {
    const translated = locale === "fr"
      ? `${recordCount[1]} enregistrements · Mis à jour à l’instant`
      : `${recordCount[1]} سجلات · تم التحديث الآن`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const selectionCount = core.match(/^(\d+) selected$/);
  if (selectionCount) {
    const translated = locale === "fr" ? `${selectionCount[1]} sélectionnés` : `تم تحديد ${selectionCount[1]}`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const enrollmentStep = core.match(/^Step (\d+) of (\d+)$/);
  if (enrollmentStep) {
    const translated = locale === "fr"
      ? `Étape ${enrollmentStep[1]} sur ${enrollmentStep[2]}`
      : `الخطوة ${enrollmentStep[1]} من ${enrollmentStep[2]}`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const currentVersion = core.match(/^Version v(\d+) is now current\.$/);
  if (currentVersion) {
    const translated = locale === "fr"
      ? `La version v${currentVersion[1]} est désormais active.`
      : `أصبح الإصدار v${currentVersion[1]} هو الإصدار الحالي.`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const minValue = core.match(/^Minimum value is ([\d.]+)\.$/);
  if (minValue) {
    const translated = locale === "fr"
      ? `La valeur minimale est ${minValue[1]}.`
      : `القيمة الدنيا هي ${minValue[1]}.`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const maxValue = core.match(/^Maximum value is ([\d.]+)\.$/);
  if (maxValue) {
    const translated = locale === "fr"
      ? `La valeur maximale est ${maxValue[1]}.`
      : `القيمة القصوى هي ${maxValue[1]}.`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const serviceStatus = core.match(/^Prediction service returned (\d+)\.$/);
  if (serviceStatus) {
    const translated = locale === "fr"
      ? `Le service de prédiction a renvoyé ${serviceStatus[1]}.`
      : `أعادت خدمة التنبؤ الرمز ${serviceStatus[1]}.`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const confidencePct = core.match(/^(\d+(?:\.\d+)?)% confidence$/);
  if (confidencePct) {
    const translated = locale === "fr"
      ? `${confidencePct[1]} % de confiance`
      : `الثقة: ${confidencePct[1]}%`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const checkedInAt = core.match(/^Checked in at (.+)$/);
  if (checkedInAt) {
    const translated = locale === "fr"
      ? `Pointé à ${checkedInAt[1]}`
      : `تم تسجيل الحضور في ${checkedInAt[1]}`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const pageCount = core.match(/^(\d+)[–-](\d+) of (\d+) · ‹ 1 2 3 ›$/);
  if (pageCount) {
    const translated = locale === "fr"
      ? `${pageCount[1]}–${pageCount[2]} sur ${pageCount[3]} · ‹ 1 2 3 ›`
      : `${pageCount[1]}–${pageCount[2]} من ${pageCount[3]} · ‹ 1 2 3 ›`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const lastEdited = core.match(/^Last edited (.+) ago$/);
  if (lastEdited) {
    const when = translateText(lastEdited[1], locale);
    const translated = locale === "fr"
      ? `Dernière modification il y a ${when}`
      : `آخر تعديل منذ ${when}`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const outOfBalance = core.match(/^Out of balance by (.+)$/);
  if (outOfBalance) {
    const translated = locale === "fr"
      ? `Déséquilibre de ${outOfBalance[1]}`
      : `فرق في الرصيد بمقدار ${outOfBalance[1]}`;
    return whitespaceStart + translated + whitespaceEnd;
  }
  const scheduledPayment = core.match(/^Scheduled payment (.+)$/);
  if (scheduledPayment) {
    const when = translateText(scheduledPayment[1], locale);
    const translated = locale === "fr"
      ? `Paiement prévu le ${when}`
      : `دفعة مجدولة في ${when}`;
    return whitespaceStart + translated + whitespaceEnd;
  }

  const direct = exact[locale]?.[core];
  if (direct) return whitespaceStart + direct + whitespaceEnd;

  const translated = core.replace(/\b[A-Za-z][A-Za-z&'-]*\b/g, (word) => {
    const hit = lookupWord(word, locale);
    if (!hit) reportMissingWord(word, locale);
    return hit || word;
  });
  return whitespaceStart + translated + whitespaceEnd;
}

function localizeElement(element: Element, locale: Locale) {
  const attributes = ["placeholder", "title", "aria-label"];
  let originals = originalAttributes.get(element);
  if (!originals) {
    originals = {};
    attributes.forEach((name) => {
      const value = element.getAttribute(name);
      if (value) originals![name] = value;
    });
    if (element instanceof HTMLOptionElement) originals.value = element.value;
    originalAttributes.set(element, originals);
  }
  attributes.forEach((name) => {
    const source = originals![name];
    if (source) element.setAttribute(name, translateText(source, locale));
  });
  if (element instanceof HTMLOptionElement && originals.value) element.value = originals.value;
}

export function localizeApplication(root: HTMLElement, locale: Locale) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (!parent || ["SCRIPT", "STYLE", "CODE", "PRE"].includes(parent.tagName)) continue;
    const current = node.nodeValue || "";
    const previousLocalized = lastLocalizedText.get(node);
    if (!originalText.has(node) || (previousLocalized !== undefined && current !== previousLocalized)) {
      originalText.set(node, current);
    }
    const source = originalText.get(node) || "";
    const translated = translateText(source, locale);
    if (node.nodeValue !== translated) node.nodeValue = translated;
    lastLocalizedText.set(node, translated);
  }
  root.querySelectorAll("*").forEach((element) => localizeElement(element, locale));
}
